window.t = function(key, vars) {
  const lang = window.__LANG || "en";
  let s = (window.I18N[lang] && window.I18N[lang][key]) || window.I18N.en[key] || key;

  if (vars) {
    Object.keys(vars).forEach(k => {
 s = s.replace(`{${k}}`, vars[k]); 
});
  }

  return s;
};
